<#
Validate rule files and build the "All rules" wiki page.
Runs in CI only (Windows PowerShell 5.1 or PowerShell 7); contributors just submit rule files.

Usage:
    powershell -NoProfile -File build/build_rules.ps1                         # validate only
    powershell -NoProfile -File build/build_rules.ps1 -Out dist/All-rules.md [-SourceUrl URL]
        -Out        write the rendered page to this path
        -SourceUrl  base URL of the rule files, e.g. $CI_PROJECT_URL/-/blob/$CI_COMMIT_SHA

Keep this file ASCII-only: Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
Non-ASCII output characters are built from [char] codes below.
#>
param(
    [string]$Out = '',
    [string]$SourceUrl = ''
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$Root     = Split-Path -Parent $PSScriptRoot
$RulesDir = Join-Path $Root 'rules'
$Utf8     = New-Object System.Text.UTF8Encoding($false)   # UTF-8 without BOM

$Dash  = [string][char]0x2014   # em dash
$Dot   = [string][char]0x00B7   # middle dot
$Up    = [string][char]0x2191   # upwards arrow
$Cross = [string][char]0x274C   # cross mark
$Check = [string][char]0x2705   # check mark

# Closed lists: changed only via MR approved by every scope Maintainer
$ScopeCodes       = @('GE', 'FE', 'BE')
$ScopeNames       = @{ GE = 'General'; FE = 'Frontend'; BE = 'Backend' }
$Statuses         = @('Active', 'Deprecated')
$RequiredFields   = @('id', 'title', 'status', 'applied_to')
$RequiredSections = @('Description', 'Bad', 'Good', 'Exceptions')
$IdPattern        = '^(GE|FE|BE)-[0-9]{3}$'
# Icons prefixed to section headings on the All rules page
$SectionIcons     = @{ Bad = "$Cross "; Good = "$Check " }

# ---------------------------------------------------------------- helpers

function Read-Text([string]$Path) {
    # Normalize line endings so Windows checkouts and other platforms behave the same
    return [System.IO.File]::ReadAllText($Path, $Utf8).Replace("`r`n", "`n")
}

function Get-RelPath([string]$Path) {
    return $Path.Substring($Root.Length).TrimStart('\', '/').Replace('\', '/')
}

function Test-Empty($Value) {
    if ($null -eq $Value) { return $true }
    if ($Value -is [System.Collections.IList]) { return $Value.Count -eq 0 }
    return [string]::IsNullOrWhiteSpace([string]$Value)
}

function Get-Anchor([string]$Heading) {
    # Heading anchor as generated by GitLab: lowercase, drop punctuation, spaces -> hyphens
    $slug = [regex]::Replace($Heading.ToLowerInvariant(), '[^\p{L}\p{N}\p{M}_ -]', '').Replace(' ', '-')
    return [regex]::Replace($slug, '-{2,}', '-')
}

# ---------------------------------------------------------------- frontmatter

function Remove-YamlComment([string]$Text) {
    # A '#' preceded by whitespace starts a comment, unless it is inside quotes
    $quote = [char]0
    for ($i = 0; $i -lt $Text.Length; $i++) {
        $c = $Text[$i]
        if ($quote -ne [char]0) { if ($c -eq $quote) { $quote = [char]0 }; continue }
        if ($c -eq '"' -or $c -eq "'") { $quote = $c; continue }
        if ($c -eq '#' -and ($i -eq 0 -or [char]::IsWhiteSpace($Text[$i - 1]))) { return $Text.Substring(0, $i) }
    }
    return $Text
}

function ConvertFrom-Scalar([string]$Text) {
    # Minimal YAML scalar: trim, then drop matching surrounding quotes
    $t = $Text.Trim()
    if ($t.Length -ge 2 -and (($t[0] -eq '"' -and $t[-1] -eq '"') -or ($t[0] -eq "'" -and $t[-1] -eq "'"))) {
        $t = $t.Substring(1, $t.Length - 2)
    }
    return $t
}

function Split-FrontMatter([string]$Text) {
    <#
    Parse the YAML subset used by rule files (inline '#' comments allowed):
        Key: value
        Key: [a, b, c]
        Key:
          - a
    Keys are case/space tolerant: "Applied to" -> applied_to.
    Returns @{ Meta = hashtable; Content = string }. Throws on malformed frontmatter.
    #>
    $meta = @{}
    $m = [regex]::Match($Text, '\A\s*---[ \t]*\n(.*?)\n---[ \t]*(\n|\z)', 'Singleline')
    if (-not $m.Success) { return @{ Meta = $meta; Content = $Text } }

    $lastKey = $null
    $lineNo = 1
    foreach ($rawLine in $m.Groups[1].Value.Split("`n")) {
        $lineNo++
        $line = (Remove-YamlComment $rawLine).TrimEnd()
        if ($line.Trim() -eq '') { continue }

        $item = [regex]::Match($line, '^\s*-\s+(.*)$')
        if ($item.Success -and $null -ne $lastKey) {
            # Block list item belonging to the previous key
            if (-not ($meta[$lastKey] -is [System.Collections.IList])) { $meta[$lastKey] = New-Object System.Collections.ArrayList }
            [void]$meta[$lastKey].Add((ConvertFrom-Scalar $item.Groups[1].Value))
            continue
        }

        $kv = [regex]::Match($line, '^([^:\s][^:]*):(?:\s+(.*))?$')
        if (-not $kv.Success) { throw "line ${lineNo}: cannot parse '$rawLine'" }
        $key = $kv.Groups[1].Value.Trim().ToLowerInvariant().Replace(' ', '_')
        $raw = $kv.Groups[2].Value.Trim()

        if ($raw.StartsWith('[')) {
            if (-not $raw.EndsWith(']')) { throw "line ${lineNo}: unclosed list '$raw'" }
            $list = New-Object System.Collections.ArrayList
            foreach ($part in $raw.Substring(1, $raw.Length - 2).Split(',')) {
                if ($part.Trim() -ne '') { [void]$list.Add((ConvertFrom-Scalar $part)) }
            }
            $meta[$key] = $list
        } elseif ($raw -eq '') {
            $meta[$key] = $null   # may be filled by block list items
        } else {
            $meta[$key] = ConvertFrom-Scalar $raw
        }
        $lastKey = $key
    }
    return @{ Meta = $meta; Content = $Text.Substring($m.Length) }
}

# ---------------------------------------------------------------- rules

function Get-Sections([string]$Content) {
    # Ordered list of @{ Name; Text } for each "## Name" section of a rule body
    $parts = [regex]::Split($Content.Trim(), '(?m)^##[ \t]+(.+?)[ \t]*$')
    $sections = New-Object System.Collections.ArrayList
    for ($i = 1; $i + 1 -lt $parts.Length; $i += 2) {
        [void]$sections.Add(@{ Name = $parts[$i]; Text = $parts[$i + 1].Trim() })
    }
    return ,$sections
}

function Format-Body([string]$Content) {
    # Description text first (no heading), then the other sections demoted under the rule heading
    $sections = Get-Sections $Content
    $blocks = New-Object System.Collections.Generic.List[string]
    foreach ($s in $sections) { if ($s.Name -ceq 'Description') { $blocks.Add($s.Text) } }
    foreach ($s in $sections) {
        if ($s.Name -ceq 'Description') { continue }
        $icon = if ($SectionIcons.ContainsKey($s.Name)) { $SectionIcons[$s.Name] } else { '' }
        $blocks.Add("#### $icon$($s.Name)`n$($s.Text)")
    }
    return $blocks -join "`n`n"
}

function Test-Rule([string]$Path, [hashtable]$Meta, [string]$Content) {
    # Return a list of error strings for one rule file
    $rel = Get-RelPath $Path
    $errors = New-Object System.Collections.ArrayList

    $missing = @($RequiredFields | Where-Object { Test-Empty $Meta[$_] })
    if ($missing.Count -gt 0) {
        [void]$errors.Add("${rel}: missing frontmatter fields [$($missing -join ', ')]")
        return ,$errors
    }

    $rid = [string]$Meta['id']
    if ($rid -cnotmatch $IdPattern) {
        [void]$errors.Add("${rel}: invalid ID '$rid' (expected GE|FE|BE-NNN)")
    } else {
        $scope = $rid.Split('-')[0]
        if ([System.IO.Path]::GetFileNameWithoutExtension($Path) -cne $rid) {
            [void]$errors.Add("${rel}: file name must equal ID ($rid.md)")
        }
        if ((Split-Path -Leaf (Split-Path -Parent $Path)) -cne $scope) {
            [void]$errors.Add("${rel}: must be in folder rules/$scope/")
        }
    }

    if ($Statuses -cnotcontains [string]$Meta['status']) {
        [void]$errors.Add("${rel}: Status '$($Meta['status'])' not in [$($Statuses -join ', ')]")
    }
    if (-not ($Meta['applied_to'] -is [System.Collections.IList])) {
        [void]$errors.Add("${rel}: 'Applied to' must be a list, e.g. [plugin, webjob]")
    }

    $names = @((Get-Sections $Content) | ForEach-Object { $_.Name })
    $missingSections = @($RequiredSections | Where-Object { $names -cnotcontains $_ })
    if ($missingSections.Count -gt 0) {
        [void]$errors.Add("${rel}: missing sections [$($missingSections -join ', ')]")
    }
    return ,$errors
}

function Get-Rules {
    $rules  = New-Object System.Collections.ArrayList
    $errors = New-Object System.Collections.ArrayList
    $seen   = @{}

    # Ordinal sort so every machine processes files in the same order
    $files = [string[]]@(Get-ChildItem -Path $RulesDir -Filter '*.md' -Recurse -File | ForEach-Object { $_.FullName })
    [Array]::Sort($files, [StringComparer]::Ordinal)

    foreach ($path in $files) {
        if ([System.IO.Path]::GetFileName($path).StartsWith('_')) { continue }   # skip helper files such as _TEMPLATE.md
        $rel = Get-RelPath $path
        try {
            $post = Split-FrontMatter (Read-Text $path)
        } catch {
            [void]$errors.Add("${rel}: cannot parse frontmatter ($($_.Exception.Message))")
            continue
        }

        $meta = $post.Meta
        if (-not (Test-Empty $meta['id'])) { $meta['id'] = ([string]$meta['id']).Trim() }

        $fileErrors = Test-Rule $path $meta $post.Content
        if ($fileErrors.Count -gt 0) { [void]$errors.AddRange($fileErrors); continue }

        $rid = $meta['id']
        if ($seen.ContainsKey($rid)) {
            [void]$errors.Add("${rel}: duplicate ID $rid (already used by $($seen[$rid]))")
            continue
        }
        $seen[$rid] = $rel

        $heading = "[$rid] $($meta['title'])"
        $meta['scope']   = $rid.Split('-')[0]
        $meta['path']    = $rel
        $meta['heading'] = $heading
        $meta['anchor']  = Get-Anchor $heading
        $meta['body']    = Format-Body $post.Content
        [void]$rules.Add($meta)
    }

    # Cross-file check: replaced_by must point to an existing rule
    foreach ($r in $rules) {
        $target = $r['replaced_by']
        if (-not (Test-Empty $target) -and -not $seen.ContainsKey([string]$target)) {
            [void]$errors.Add("$($r['path']): 'Replaced by' points to unknown ID $target")
        }
    }

    $sorted = @($rules | Sort-Object -Property @{ Expression = { [array]::IndexOf($ScopeCodes, $_['scope']) } }, @{ Expression = { $_['id'] } })
    return @{ Rules = $sorted; Errors = $errors }
}

# ---------------------------------------------------------------- page layout

function Format-Page([object[]]$Rules, [string]$BaseUrl) {
    # Layout of the "All rules" wiki page. Edit here to change the output.
    $active     = @($Rules | Where-Object { $_['status'] -ceq 'Active' })
    $deprecated = @($Rules | Where-Object { $_['status'] -ceq 'Deprecated' })
    $byId = @{}
    foreach ($r in $Rules) { $byId[$r['id']] = $r }
    $BaseUrl = $BaseUrl.TrimEnd('/')

    $o = New-Object System.Collections.Generic.List[string]
    $o.Add('_Generated from `rules/` by CI on every merge. Do not edit this page: changes are overwritten. To add or change a rule, see [Contributing](Contributing)._')
    $o.Add('')
    $o.Add("**$($active.Count) active** $Dot $($deprecated.Count) deprecated")
    $o.Add('')
    $o.Add('## Table of contents')
    $o.Add('')
    foreach ($code in $ScopeCodes) {
        $inScope = @($active | Where-Object { $_['scope'] -ceq $code })
        if ($inScope.Count -eq 0) { continue }
        $o.Add("- **$code $Dash $($ScopeNames[$code])**")
        foreach ($r in $inScope) { $o.Add("    - [$($r['id'])](#$($r['anchor'])) $Dot $($r['title'])") }
    }
    if ($deprecated.Count -gt 0) { $o.Add('- [Deprecated rules](#deprecated-rules)') }
    $o.Add('')

    foreach ($code in $ScopeCodes) {
        $inScope = @($active | Where-Object { $_['scope'] -ceq $code })
        if ($inScope.Count -eq 0) { continue }
        $o.Add("## $code $Dash $($ScopeNames[$code])")
        $o.Add('')
        foreach ($r in $inScope) {
            $tags = @($r['applied_to'] | ForEach-Object { '`' + $_ + '`' }) -join ' '
            $o.Add("### $($r['heading'])")
            $o.Add('')
            $o.Add("_Applied to:_ $tags")
            $o.Add('')
            $o.Add($r['body'])
            $o.Add('')
            $o.Add("[$Up Back to top](#table-of-contents)")
            $o.Add('')
        }
    }

    if ($deprecated.Count -gt 0) {
        $o.Add('## Deprecated rules')
        $o.Add('')
        $o.Add('| ID | Title | Replaced by |')
        $o.Add('| --- | --- | --- |')
        foreach ($r in $deprecated) {
            $id = if ($BaseUrl) { "[$($r['id'])]($BaseUrl/$($r['path']))" } else { $r['id'] }
            $by = '-'
            if (-not (Test-Empty $r['replaced_by'])) {
                $succ = $byId[[string]$r['replaced_by']]
                $by = if ($succ['status'] -ceq 'Active') { "[$($succ['id'])](#$($succ['anchor']))" } else { [string]$r['replaced_by'] }
            }
            $o.Add("| $id | $($r['title']) | $by |")
        }
    }

    # Collapse blank-line runs (also inside rule bodies) and trim
    return [regex]::Replace(($o -join "`n"), '\n{3,}', "`n`n").Trim() + "`n"
}

# ---------------------------------------------------------------- main

function Invoke-Main {
    $result = Get-Rules
    if ($result.Errors.Count -gt 0) {
        Write-Host 'Rule validation failed:'
        foreach ($e in $result.Errors) { Write-Host "  - $e" }
        return 1
    }
    $rules = $result.Rules

    if ($Out) {
        $outPath = if ([System.IO.Path]::IsPathRooted($Out)) { $Out } else { Join-Path (Get-Location) $Out }
        $dir = Split-Path -Parent $outPath
        if ($dir -and -not (Test-Path $dir)) { [void](New-Item -ItemType Directory -Path $dir) }
        # Always UTF-8 without BOM + LF so the output is identical everywhere
        [System.IO.File]::WriteAllText($outPath, (Format-Page $rules $SourceUrl), $Utf8)
        Write-Host "OK: $($rules.Count) rules valid, page written to $Out."
    } else {
        Write-Host "OK: $($rules.Count) rules valid."
    }
    return 0
}

try { [Console]::OutputEncoding = $Utf8 } catch { }   # print non-ASCII titles correctly; ignore when there is no console
exit (Invoke-Main)
